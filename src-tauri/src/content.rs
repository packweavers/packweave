fn reset_source(source: &mut SourceFile) {
    source.version_number.clear();
    source.filename.clear();
    source.download_url.clear();
    source.sha1 = None;
    source.sha512 = None;
    source.file_size = 0;
}

pub fn set_source_version(
    pack_dir: &Path,
    key: &str,
    provider: ProviderId,
    version: Option<String>,
) -> Result<bool> {
    for mut item in read_all(pack_dir) {
        if !matches(&item, key) {
            continue;
        }
        if provider == item.preferred {
            return match version {
                Some(version) => set_version(pack_dir, key, version),
                None => Ok(false),
            };
        }
        let Some(source) = item.sources.get_mut(&provider) else {
            return Ok(false);
        };
        source.pinned = version.is_some();
        source.version_id = version.unwrap_or_default();
        reset_source(source);
        add_item(pack_dir, &item)?;
        return Ok(true);
    }
    Ok(false)
}

pub fn set_version(pack_dir: &Path, key: &str, version: String) -> Result<bool> {
    for mut item in read_all(pack_dir) {
        if matches(&item, key) {
            let pref = item.preferred;
            for (provider, source) in item.sources.iter_mut() {
                if *provider != pref && !source.pinned {
                    source.version_id.clear();
                    reset_source(source);
                }
            }
            if let Some(s) = item.sources.get_mut(&pref) {
                s.version_id = version;
                s.version_number.clear();
                s.filename.clear();
                s.download_url.clear();
                s.sha1 = None;
                s.sha512 = None;
                s.file_size = 0;
            }
            add_item(pack_dir, &item)?;
            return Ok(true);
        }
    }
    Ok(false)
}

pub fn add_alt(pack_dir: &Path, key: &str, provider: ProviderId, id: &str) -> Result<bool> {
    for mut item in read_all(pack_dir) {
        if matches(&item, key) {
            if item.sources.contains_key(&provider) {
                return Ok(false);
            }
            item.sources.insert(
                provider,
                SourceFile {
                    id: Some(id.into()),
                    ..Default::default()
                },
            );
            item.explicit = true;
            add_item(pack_dir, &item)?;
            return Ok(true);
        }
    }
    Ok(false)
}

pub fn remove_alt(pack_dir: &Path, key: &str, provider: ProviderId) -> Result<bool> {
    for mut item in read_all(pack_dir) {
        if matches(&item, key) {
            if provider == item.preferred {
                return Ok(false);
            }
            if item.sources.remove(&provider).is_none() {
                return Ok(false);
            }
            add_item(pack_dir, &item)?;
            return Ok(true);
        }
    }
    Ok(false)
}

pub fn set_preferred(pack_dir: &Path, key: &str, provider: ProviderId) -> Result<bool> {
    for mut item in read_all(pack_dir) {
        if matches(&item, key) {
            if item.preferred == provider || !item.sources.contains_key(&provider) {
                return Ok(false);
            }
            item.preferred = provider;
            item.explicit = true;
            add_item(pack_dir, &item)?;
            return Ok(true);
        }
    }
    Ok(false)
}

pub fn write_resolved(
    pack_dir: &Path,
    manifest: &Manifest,
    resolved: &[ContentItem],
) -> Result<()> {
    let base = content_dir(pack_dir);
    for sub in ProjectType::ALL.map(ProjectType::content_dir) {
        crate::util::delete_dir_all(&base.join(sub))?;
    }
    for item in resolved {
        add_item(pack_dir, item)?;
    }
    write_summary(pack_dir, manifest, resolved)?;
    write_index(pack_dir)?;
    Ok(())
}

fn index_text(mut files: Vec<(String, String)>) -> Result<String> {
    files.sort_by(|a, b| a.0.cmp(&b.0));
    let arr: Vec<serde_json::Value> = files
        .into_iter()
        .map(|(path, sha1)| serde_json::json!({ "path": path, "sha1": sha1 }))
        .collect();
    Ok(format!(
        "{}\n",
        serde_json::to_string_pretty(&serde_json::json!({ "files": arr }))?
    ))
}

fn content_item_path(path: &str) -> bool {
    path.strip_prefix(&format!("{CONTENT_DIR}/"))
        .and_then(|rest| rest.split_once('/'))
        .is_some_and(|(sub, name)| {
            ProjectType::ALL
                .map(ProjectType::content_dir)
                .contains(&sub)
                && !name.contains('/')
                && name.ends_with(".json")
        })
}

fn indexed(filter: &ExportFilter, path: &str) -> bool {
    if path == crate::dist::PACK_JAR {
        return true;
    }
    let scoped = path.starts_with(&format!("{CONTENT_DIR}/"))
        || path.starts_with(&format!("{}/", instance::OVERRIDES_DIR))
        || (!path.contains('/') && crate::packignore::is_document(path));
    scoped && !filter.skips(path)
}

fn blob_sha1s() -> &'static Mutex<HashMap<String, String>> {
    static CACHE: OnceLock<Mutex<HashMap<String, String>>> = OnceLock::new();
    CACHE.get_or_init(Default::default)
}

pub(crate) fn stage_index(pack_dir: &Path) -> Result<()> {
    let tracked = crate::git::tracks(pack_dir, INDEX_FILE);
    if !tracked
        && (!pack_dir.join(INDEX_FILE).is_file() || crate::git::ignored(pack_dir, INDEX_FILE))
    {
        return Ok(());
    }
    let staged = crate::git::staged_files(pack_dir)?;
    let mut export = None;
    if let Some((_, oid)) = staged.iter().find(|(path, _)| path == PACKWEAVEIGNORE_FILE) {
        crate::git::each_blob(pack_dir, std::slice::from_ref(oid), |_, bytes| {
            export = Some(String::from_utf8_lossy(bytes).into_owned());
        })?;
    }
    let tracked: HashSet<String> = staged.iter().map(|(path, _)| path.clone()).collect();
    let filter = ExportFilter::committed(pack_dir, tracked, export.as_deref());
    let wanted: Vec<&(String, String)> = staged
        .iter()
        .filter(|(path, _)| indexed(&filter, path))
        .collect();
    let mut cache = blob_sha1s().lock().unwrap_or_else(PoisonError::into_inner);
    let mut reads: Vec<String> = Vec::new();
    let mut items: HashSet<String> = HashSet::new();
    for (path, oid) in &wanted {
        let item = content_item_path(path);
        if item {
            items.insert(oid.clone());
        }
        if (item || !cache.contains_key(oid)) && !reads.contains(oid) {
            reads.push(oid.clone());
        }
    }
    let mut disabled: HashSet<String> = HashSet::new();
    crate::git::each_blob(pack_dir, &reads, |i, bytes| {
        let oid = &reads[i];
        cache.insert(oid.clone(), hex::encode(Sha1::digest(bytes)));
        if items.contains(oid)
            && serde_json::from_slice::<ContentItem>(bytes).is_ok_and(|item| item.disabled)
        {
            disabled.insert(oid.clone());
        }
    })?;
    let mut files: Vec<(String, String)> = Vec::new();
    for (path, oid) in wanted {
        if content_item_path(path) && disabled.contains(oid) {
            continue;
        }
        if let Some(sha1) = cache.get(oid) {
            files.push((path.clone(), sha1.clone()));
        }
    }
    drop(cache);
    crate::git::stage_blob(pack_dir, INDEX_FILE, index_text(files)?.as_bytes())
}

pub(crate) fn write_index(pack_dir: &Path) -> Result<()> {
    let filter = ExportFilter::load(pack_dir);
    let disabled: std::collections::HashSet<String> = read_all(pack_dir)
        .iter()
        .filter(|i| i.disabled)
        .map(item_rel_path)
        .collect();
    let mut files: Vec<(String, String)> = Vec::new();
    for file in filter
        .tree(pack_dir, CONTENT_DIR)
        .into_iter()
        .chain(filter.tree(pack_dir, instance::OVERRIDES_DIR))
        .chain(filter.documents(pack_dir))
    {
        if disabled.contains(&file.rel) {
            continue;
        }
        if let Ok(bytes) = std::fs::read(&file.path) {
            let mut hasher = Sha1::new();
            hasher.update(&bytes);
            files.push((file.rel, hex::encode(hasher.finalize())));
        }
    }
    if let Ok(bytes) = std::fs::read(pack_dir.join(crate::dist::PACK_JAR)) {
        files.push((
            crate::dist::PACK_JAR.to_string(),
            hex::encode(Sha1::digest(&bytes)),
        ));
    }
    std::fs::write(pack_dir.join(INDEX_FILE), index_text(files)?)?;
    Ok(())
}

fn generated(path: &Path) -> bool {
    std::fs::read_to_string(path).is_ok_and(|text| text.trim_end().ends_with(SUMMARY_MARKER))
}

pub(crate) fn retire_generated_readme(pack_dir: &Path) -> Result<()> {
    let old = pack_dir.join(OLD_SUMMARY_FILE);
    if generated(&old) {
        crate::util::delete_file(&old)
            .map_err(|e| anyhow::anyhow!("Couldn't remove {OLD_SUMMARY_FILE}: {e}"))?;
    }
    Ok(())
}

fn write_summary(pack_dir: &Path, manifest: &Manifest, resolved: &[ContentItem]) -> Result<()> {
    let path = pack_dir.join(SUMMARY_FILE);
    if !manifest.packweave_md {
        if generated(&path) {
            crate::util::delete_file(&path)?;
        }
        return Ok(());
    }
    if path.exists() && !generated(&path) {
        return Ok(());
    }
    let count = |ty: ProjectType, explicit: bool| {
        resolved
            .iter()
            .filter(|i| i.project_type == ty && i.explicit == explicit)
            .count()
    };
    let mods = count(ProjectType::Mod, true);
    let deps = count(ProjectType::Mod, false);
    let rps = count(ProjectType::Resourcepack, true) + count(ProjectType::Resourcepack, false);
    let shaders = count(ProjectType::Shader, true) + count(ProjectType::Shader, false);
    let datapacks = count(ProjectType::Datapack, true) + count(ProjectType::Datapack, false);
    let noun = |n: usize, s: &str, p: &str| (if n == 1 { s } else { p }).to_string();
    let mut segs = vec![if deps > 0 {
        format!(
            "{mods} {} ({deps} {})",
            noun(mods, "mod", "mods"),
            noun(deps, "dependency", "dependencies")
        )
    } else {
        format!("{mods} {}", noun(mods, "mod", "mods"))
    }];
    if rps > 0 {
        segs.push(format!(
            "{rps} {}",
            noun(rps, "resource pack", "resource packs")
        ));
    }
    if shaders > 0 {
        segs.push(format!("{shaders} {}", noun(shaders, "shader", "shaders")));
    }
    if datapacks > 0 {
        segs.push(format!(
            "{datapacks} {}",
            noun(datapacks, "data pack", "data packs")
        ));
    }
    let loader = match &manifest.loader_version {
        Some(v) => format!("{} {}", manifest.loader, v),
        None => manifest.loader.clone(),
    };
    let mut md = String::new();
    md.push_str(&format!("# {}\n\n", manifest.name));
    md.push_str(&format!(
        "**Minecraft {} · {}**, {}\n\n",
        manifest.minecraft,
        loader,
        segs.join(", ")
    ));
    md.push_str("## Contents\n\n");
    let mut rows: Vec<&ContentItem> = resolved.iter().filter(|i| i.explicit).collect();
    rows.sort_by_key(|i| i.name.to_lowercase());
    for item in rows {
        let pref = item.active();
        let version = pref.map(|s| s.version_number.clone()).unwrap_or_default();
        let slug = pref.map(|s| s.slug.clone()).unwrap_or_default();
        let link = if item.preferred == ProviderId::Modrinth {
            format!("https://modrinth.com/project/{slug}")
        } else {
            String::new()
        };
        let vsuffix = if version.is_empty() {
            String::new()
        } else {
            format!(" `{version}`")
        };
        if link.is_empty() {
            md.push_str(&format!(
                "- {}{} ({})\n",
                item.name, vsuffix, item.preferred
            ));
        } else {
            md.push_str(&format!("- [{}]({}){}\n", item.name, link, vsuffix));
        }
    }
    md.push('\n');
    md.push_str(SUMMARY_MARKER);
    md.push('\n');
    std::fs::write(&path, md)?;
    Ok(())
}

pub fn to_locked(item: &ContentItem) -> LockedMod {
    LockedMod {
        name: item.name.clone(),
        project_id: item.project_id(),
        key: item_rel_path(item),
        slug: item.active().map(|s| s.slug.clone()).unwrap_or_default(),
        project_type: item.project_type,
        preferred: item.preferred,
        sources: item.sources.clone(),
        dependency_type: if item.explicit {
            DepType::Explicit
        } else {
            DepType::Dependency
        },
        dependents: item.dependents.clone(),
        optional_dependents: item.optional_dependents.clone(),
        client_side: item.client_side.clone(),
        server_side: item.server_side.clone(),
        disabled: item.disabled,
        pinned: item.pinned,
        no_bundle: item.no_bundle,
    }
}
