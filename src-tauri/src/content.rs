pub const CONTENT_DIR: &str = "content";
pub const INDEX_FILE: &str = "index.json";
const SUMMARY_MARKER: &str = "_Generated by packweave._";
const SUMMARY_FILE: &str = "PACKWEAVE.md";
const OLD_SUMMARY_FILE: &str = "README.md";

#[derive(Debug, Clone, Default, Serialize, Deserialize, TS)]
#[serde(rename_all = "camelCase")]
#[ts(export, export_to = "types.ts")]
pub struct ContentItem {
    #[serde(default)]
    pub name: String,
    #[serde(skip)]
    pub project_type: ProjectType,
    #[serde(skip)]
    pub file: String,
    #[serde(default = "auto_side")]
    pub side: String,
    #[serde(default)]
    pub explicit: bool,
    #[serde(default)]
    pub disabled: bool,
    #[serde(default, skip_serializing_if = "crate::util::is_false")]
    pub pinned: bool,
    #[serde(default)]
    pub preferred: ProviderId,
    #[serde(default)]
    pub sources: BTreeMap<ProviderId, SourceFile>,
    #[serde(default)]
    pub dependents: Vec<String>,
    #[serde(default, skip_serializing_if = "Vec::is_empty")]
    pub optional_dependents: Vec<String>,
    #[serde(default = "crate::util::required")]
    pub client_side: String,
    #[serde(default = "crate::util::required")]
    pub server_side: String,
    #[serde(default, skip_serializing_if = "crate::util::is_false")]
    pub no_bundle: bool,
}

impl ContentItem {
    pub fn active(&self) -> Option<&SourceFile> {
        self.sources.get(&self.preferred)
    }

    pub fn project_id(&self) -> String {
        self.active()
            .and_then(|s| s.id.clone())
            .filter(|x| !x.is_empty())
            .or_else(|| {
                self.active()
                    .map(|s| s.slug.clone())
                    .filter(|x| !x.is_empty())
            })
            .unwrap_or_else(|| file_stem(self))
    }
}

fn auto_side() -> String {
    "auto".into()
}

pub fn type_dir(project_type: ProjectType) -> &'static str {
    project_type.content_dir()
}

fn type_from_dir(sub: &str) -> ProjectType {
    ProjectType::from_content_dir(sub)
}

pub fn content_dir(pack_dir: &Path) -> PathBuf {
    pack_dir.join(CONTENT_DIR)
}

fn item_path(pack_dir: &Path, project_type: ProjectType, slug: &str) -> PathBuf {
    content_dir(pack_dir)
        .join(type_dir(project_type))
        .join(format!("{slug}.json"))
}

pub fn file_stem(item: &ContentItem) -> String {
    if !item.file.is_empty() {
        return item.file.clone();
    }
    let pref_slug = item.active().map(|s| s.slug.as_str()).unwrap_or("");
    slug_for(pref_slug, &item.name)
}

pub fn without_duplicates(items: Vec<ContentItem>) -> Vec<ContentItem> {
    let ids = |item: &ContentItem| -> Vec<(ProviderId, String)> {
        item.sources
            .iter()
            .filter_map(|(p, s)| s.id.clone().filter(|id| !id.is_empty()).map(|id| (*p, id)))
            .collect()
    };
    let mut claimed: HashSet<(ProviderId, String)> = HashSet::new();
    let mut dropped: HashSet<usize> = HashSet::new();
    for disabled in [false, true] {
        for (index, item) in items.iter().enumerate() {
            if !item.explicit || item.disabled != disabled {
                continue;
            }
            let own = ids(item);
            if own.iter().any(|id| claimed.contains(id)) {
                dropped.insert(index);
            } else {
                claimed.extend(own);
            }
        }
    }
    items
        .into_iter()
        .enumerate()
        .filter(|(index, _)| !dropped.contains(index))
        .map(|(_, item)| item)
        .collect()
}

pub fn assign_files(items: &mut [ContentItem]) {
    let mut taken: HashSet<(ProjectType, String)> = HashSet::new();
    for item in items.iter().filter(|i| !i.file.is_empty()) {
        taken.insert((item.project_type, item.file.clone()));
    }
    let mut kept: HashSet<(ProjectType, String)> = HashSet::new();
    for item in items.iter_mut() {
        let stem = file_stem(item);
        if !item.file.is_empty() && kept.insert((item.project_type, stem.clone())) {
            continue;
        }
        let mut candidate = stem.clone();
        let mut n = 2;
        while taken.contains(&(item.project_type, candidate.clone())) {
            candidate = format!("{stem}-{n}");
            n += 1;
        }
        taken.insert((item.project_type, candidate.clone()));
        kept.insert((item.project_type, candidate.clone()));
        item.file = candidate;
    }
}

fn slug_for(pref_slug: &str, name: &str) -> String {
    let base = if !pref_slug.is_empty() {
        pref_slug
    } else {
        name
    };
    let s: String = base
        .to_lowercase()
        .chars()
        .map(|c| {
            if c.is_ascii_alphanumeric() || c == '-' || c == '_' {
                c
            } else {
                '-'
            }
        })
        .collect();
    if s.is_empty() {
        "item".into()
    } else {
        s
    }
}

pub fn item_rel_path(item: &ContentItem) -> String {
    format!(
        "{CONTENT_DIR}/{}/{}.json",
        type_dir(item.project_type),
        file_stem(item)
    )
}

pub fn locked_rel_path(m: &LockedMod) -> String {
    if !m.key.is_empty() {
        return m.key.clone();
    }
    let pref_slug = m.active().map(|s| s.slug.as_str()).unwrap_or("");
    format!(
        "{CONTENT_DIR}/{}/{}.json",
        type_dir(m.project_type),
        slug_for(pref_slug, &m.name)
    )
}

pub fn matches(item: &ContentItem, key: &str) -> bool {
    item.sources
        .values()
        .any(|s| s.id.as_deref() == Some(key) || s.url.as_deref() == Some(key))
        || item.active().map(|s| s.slug == key).unwrap_or(false)
        || file_stem(item) == key
        || item_rel_path(item) == key
}

pub fn name_of(pack_dir: &Path, key: &str) -> String {
    read_all(pack_dir)
        .into_iter()
        .find(|i| matches(i, key))
        .map(|i| i.name)
        .unwrap_or_else(|| key.to_string())
}

pub fn names_label(pack_dir: &Path, keys: &[String]) -> String {
    match keys {
        [] => "nothing".into(),
        [one] => name_of(pack_dir, one),
        [a, b] => {
            format!("{} and {}", name_of(pack_dir, a), name_of(pack_dir, b))
        }
        many => format!("{} items", many.len()),
    }
}

pub fn read_all(pack_dir: &Path) -> Vec<ContentItem> {
    scan(pack_dir).0
}

pub fn read_all_checked(pack_dir: &Path) -> Result<Vec<ContentItem>> {
    let (items, broken) = scan(pack_dir);
    match broken.first() {
        Some(path) => {
            anyhow::bail!("{path} isn't valid. Fix it or finish the merge, then try again.")
        }
        None => Ok(items),
    }
}

fn scan(pack_dir: &Path) -> (Vec<ContentItem>, Vec<String>) {
    let mut items = Vec::new();
    let mut broken = Vec::new();
    for sub in ProjectType::ALL.map(ProjectType::content_dir) {
        let dir = content_dir(pack_dir).join(sub);
        let entries = match std::fs::read_dir(&dir) {
            Ok(e) => e,
            Err(_) => continue,
        };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) != Some("json") {
                continue;
            }
            let Ok(text) = std::fs::read_to_string(&path) else {
                continue;
            };
            let rel = format!(
                "{CONTENT_DIR}/{sub}/{}",
                path.file_name().unwrap_or_default().to_string_lossy()
            );
            let item = match serde_json::from_str::<ContentItem>(&text) {
                Ok(item) => Some(item),
                Err(_) if crate::lenient::has_conflict(&text) => None,
                Err(_) => repair_item(&path, &text),
            };
            match item {
                Some(mut item) => {
                    item.project_type = type_from_dir(sub);
                    item.file = path
                        .file_stem()
                        .map(|s| s.to_string_lossy().into_owned())
                        .unwrap_or_default();
                    items.push(item);
                }
                None => broken.push(rel),
            }
        }
    }
    items.sort_by_key(|i| i.name.to_lowercase());
    (items, broken)
}

fn repair_item(path: &Path, text: &str) -> Option<ContentItem> {
    let base = serde_json::to_value(serde_json::from_str::<ContentItem>("{}").ok()?).ok()?;
    let (item, _) = crate::lenient::repair::<ContentItem>(text, base)?;
    let fixed = serde_json::to_string_pretty(&item).ok()?;
    let _ = std::fs::write(path, format!("{fixed}\n"));
    Some(item)
}

pub fn add_item(pack_dir: &Path, item: &ContentItem) -> Result<()> {
    let path = item_path(pack_dir, item.project_type, &file_stem(item));
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(&path, format!("{}\n", serde_json::to_string_pretty(item)?))?;
    Ok(())
}

pub fn remove_item(pack_dir: &Path, key: &str) -> Result<()> {
    for item in read_all(pack_dir) {
        if matches(&item, key) {
            crate::util::delete_file(&item_path(pack_dir, item.project_type, &file_stem(&item)))?;
        }
    }
    Ok(())
}

pub fn delete_content(pack_dir: &Path, keys: &[String]) -> Result<()> {
    let items = read_all(pack_dir);
    let target: std::collections::HashSet<String> = items
        .iter()
        .filter(|it| keys.iter().any(|k| matches(it, k)))
        .map(|it| it.project_id())
        .collect();
    let enabled: std::collections::HashSet<String> = items
        .iter()
        .filter(|i| !i.disabled)
        .map(|i| i.project_id())
        .collect();
    for mut item in items {
        if !target.contains(&item.project_id()) {
            continue;
        }
        let needed = item
            .dependents
            .iter()
            .any(|d| !target.contains(d) && enabled.contains(d));
        if needed {
            item.disabled = true;
            add_item(pack_dir, &item)?;
        } else {
            crate::util::delete_file(&item_path(pack_dir, item.project_type, &file_stem(&item)))?;
        }
    }
    Ok(())
}

